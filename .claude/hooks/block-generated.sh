#!/usr/bin/env bash
# PreToolUse hook (Write|Edit|MultiEdit). Refuses edits to files Claude must never
# hand-write, and says which command produces them instead.
#
#   - build_runner outputs (freezed, json_serializable, injectable, auto_route,
#     hive_ce): *.g.dart, *.freezed.dart, *.gr.dart, *.config.dart
#   - gen-l10n outputs: lib/l10n/app_localizations*.dart
#   - flutterfire outputs: firebase_options*.dart, google-services.json,
#     GoogleService-Info.plist (CLAUDE.md: the owner runs `flutterfire configure`)
#   - pubspec.lock (owned by `dart pub get`)
#   - Flutter tool outputs, rewritten on every pub get / build:
#     GeneratedPluginRegistrant.*, ios/Flutter/Generated.xcconfig,
#     flutter_export_environment.sh, .flutter-plugins-dependencies
#   - design/** (CLAUDE.md: design exports are read-only for Claude)
#
# Deliberately allowed: hive_adapters.g.yaml (hive_ce's schema file; it may
# need a hand edit during a migration, see .claude/rules/hive.md).
#
# Exit 2 blocks the tool call and shows stderr to Claude.
set -uo pipefail

# shellcheck source=lib/hook_input.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/hook_input.sh"

FILE="$(hook_get file_path)"
[[ -z "$FILE" ]] && exit 0

ROOT="$(nesty_root)"
BASE="$(basename "$FILE")"
REL="${FILE#"$ROOT"/}"
PKG="$(package_dir_of "$FILE")"
PKG_REL="${PKG#"$ROOT"/}"
[[ -z "$PKG_REL" ]] && PKG_REL="<package>"

block() {
  echo "Blocked by .claude/hooks/block-generated.sh: $1" >&2
  exit 2
}

case "$REL" in
  design/*)
    block "design/ holds the owner's design exports and is read-only for Claude (CLAUDE.md). If a design is missing, use design/tokens.json + spec §12 and leave a // TODO(design): note in code instead." ;;
esac

case "$BASE" in
  firebase_options*.dart|google-services.json|GoogleService-Info.plist)
    block "$BASE is produced by \`flutterfire configure\`, which only the owner runs (CLAUDE.md). Never hand-write or invent Firebase config; ask the user to run it." ;;
  pubspec.lock)
    block "pubspec.lock is owned by pub. Change pubspec.yaml (only with a reason in docs/PROGRESS.md, CLAUDE.md rule 9) and run \`dart pub get\` at the repo root." ;;
  *.g.dart|*.freezed.dart|*.gr.dart|*.config.dart)
    block "$BASE is generated. Edit the annotated source (@freezed / @JsonSerializable / @injectable / @AutoRouterConfig / @GenerateAdapters) and run: cd $PKG_REL && dart run build_runner build" ;;
  GeneratedPluginRegistrant.*|Generated.xcconfig|flutter_export_environment.sh|.flutter-plugins-dependencies)
    block "$BASE is written by the Flutter tool on every \`flutter pub get\` / build and is gitignored. Change pubspec.yaml, the Gradle files or the Xcode build settings instead." ;;
esac

case "$FILE" in
  */lib/l10n/app_localizations*.dart|lib/l10n/app_localizations*.dart)
    block "$BASE is generated by gen-l10n. Edit lib/l10n/app_en.arb (and the other locale .arb files) and run: cd $PKG_REL && flutter gen-l10n" ;;
esac

exit 0
