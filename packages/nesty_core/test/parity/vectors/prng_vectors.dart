// Reference vectors for Prng (lib/src/prng/prng.dart): spec §6.5,
// docs/plans/m1-core-design.md §3 and §5.
//
// Produced by an independent Python 3 implementation written from the
// definitions below, not from the Dart code. Its xoshiro128** core,
// splitmix32 and MurmurHash3_x86_32 were first checked against a C
// transcription of the upstream reference code (xoshiro128starstar.c 1.1 by
// Blackman and Vigna; MurmurHash3.cpp from smhasher) and against the 20
// published MurmurHash3_x86_32 test vectors. Python integers are exact, so
// the reference has no 2^53 or 32-bit-bitwise concerns.
//
// What the vectors pin. Changing any of it changes every generated level, so
// it needs a Generator.version bump and new goldens (spec §6.5):
// - Seeding: lo = seed % 2^32, hi = seed ~/ 2^32. A is a splitmix32 stream
//   started at lo and B one started at hi ^ 0x510E527F, where splitmix32
//   steps x = x + 0x9E3779B9 (mod 2^32) and outputs fmix32(x). The state is
//   (A1, A2 ^ B1, A3 ^ B2, A4 ^ B3).
// - nextU32: xoshiro128** 1.1.
// - nextInt(n): t = 2^32 mod n; draw r until r >= t; return r % n.
// - nextIntBetween(a, b) = a + nextInt(b - a + 1).
// - nextBool: nextU32() >= 2^31.
// - shuffle: Durstenfeld, i from length - 1 down to 1, j = nextInt(i + 1).
// - pick: list[nextInt(length)].
// - derive(seed, a, b): MurmurHash3_x86_32 over the little-endian u32 words
//   [lo, hi, a, b] with seed 0xA54FF53A.
//
// JSON-shaped consts, so test/parity/ compares them unchanged on the VM, in
// dart2js (chrome, node) and in dart2wasm. Never edit a value to match the
// Dart output: if a definition changes on purpose, recompute every vector
// with an independent implementation (the one-off script is not kept).
