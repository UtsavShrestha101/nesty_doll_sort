/// The A* search behind `Solver` and `SolverRun` (spec §6.2–§6.3,
/// docs/plans/m1-core-design.md §3).
///
/// - **Cost and heuristic:** every move costs 1; `h = nestsOnBoard −
///   setsRemaining`. A merge lowers h by exactly 1 (a completing merge
///   removes two nests and one remaining set), a placement leaves it, so h
///   is consistent and never overestimates.
/// - **Open list:** a [BucketQueue] over `f = g + h`, LIFO within a bucket.
/// - **Goal at generation:** the last move of any win is a completing merge
///   from a node with h = 1, whose f is the lowest in the queue, so a win
///   found when it is generated is already optimal.
/// - **States:** every stored board is in [CanonicalBoard] form, hashed to
///   `Hash64` and kept in a [VisitedTable] that confirms every hash hit by
///   comparing the stored board. A cheaper path to a state that wasn't
///   expanded yet reroutes it and pushes it again; the stale queue entry is
///   skipped when popped.
/// - **Pruning (spec §6.3, design A30):** a lone nest never moves from a
///   free slot into an empty free slot (the board would only permute free
///   slots), and each source makes at most one placement into an empty free
///   slot (all of them give the same canonical board). Likewise a merge
///   between two free slots is tried in one direction only: A inside B and
///   B swallowing A leave the same merged nest in one free slot and the
///   other empty. None of these removes a canonical state from the
///   reachable set, so exhausting the queue still proves a level
///   unsolvable.
/// - **Budget:** at most [budget] stored states (a node is a distinct
///   canonical state stored, design A5). A state that doesn't fit ends the
///   search as `unknown`, never `unsolvable`.
/// - **Solution:** the stored moves are moves between canonical boards, so
///   [_solution] replays them on the real starting board, taking at each
///   step the first legal move (in `Rules.legalMoves` order) that reaches
///   the next stored state. The result is a line of real moves that
///   `Rules.tryMove` plays to `Won`.
///
/// Moves are generated by the rules kernel, in `Rules.legalMoves` order, and
/// applied by it, so the solver runs the one §4 implementation (CLAUDE.md
/// rule 2). All arithmetic is small ints and typed lists, so the result is
/// identical on the VM and the web.
///
/// Internal to nesty_core.
final class AStarSearch implements NodeKeyMatcher {
  AStarSearch(GameState state, this.budget)
    : _start = GameStateBoard.peek(state),
      _layout = GameStateBoard.peek(state).layout,
      _parent = GameStateBoard.thaw(state),
      _child = GameStateBoard.thaw(state),
      _canonical = CanonicalBoard(
        GameStateBoard.peek(state).layout,
        GameStateBoard.peek(state).extraCount,
      ),
      _moves = Int32List(
        Kernel.legalMoveCapacity(GameStateBoard.peek(state).layout),
      ) {
    _store = NodeStore(_canonical.keyWords, budget);
    _key = Int32List(_canonical.keyWords);
    final root = _child;
    _canonical.canonicalize(root);
    _hashKey(root);
    final h = Kernel.nestCount(root) - (_layout.totalSets - root.completedSets);
    final node = _store.add(_key, -1, 0, 0, 0, h);
    if (Kernel.isWon(root)) {
      _finish(SolveVerdict.solved, const []);
      return;
    }
    _table.add(_canonical.hashHi, _canonical.hashLo, node);
    _queue.push(h, node);
  }

  /// The most states the search may store.
  final int budget;

  // The real starting board, kept for replaying the solution.
  final Board _start;
  final BoardLayout _layout;
  // The node being expanded, and the successor being built.
  final Board _parent;
  final Board _child;
  final CanonicalBoard _canonical;
  late final NodeStore _store;
  // The key of the board being looked up.
  late final Int32List _key;
  final VisitedTable _table = VisitedTable();
  final BucketQueue _queue = BucketQueue();
  final Int32List _moves;

  int _expansions = 0;
  int _successors = 0;
  int _reroutes = 0;
  SolveResult? _result;

  /// True once the search found a win, proved there is none, or ran out of
  /// budget.
  bool get isDone => _result != null;

  /// States stored so far (design A5).
  int get nodes => _store.length;

  /// Nodes expanded so far.
  int get expansions => _expansions;

  /// Successors generated so far, after pruning, duplicates included.
  int get successors => _successors;

  /// Times a cheaper path to a waiting state rerouted it.
  int get reroutes => _reroutes;

  /// The result, once [isDone].
  SolveResult? get result => _result;

  /// Bytes held by the search's typed lists (arena, visited table, queue),
  /// for the memory budget of design §5.
  int get bytes => _store.bytes + _table.bytes + _queue.bytes;

  /// An upper bound on the most bytes the search's typed lists held at
  /// once: [bytes] plus the moments the visited table and the queue held an
  /// old list next to its doubled one. The arena grows in chunks and never
  /// holds two copies.
  int get peakBytes => _store.bytes + _table.peakBytes + _queue.peakBytes;

  /// Expands nodes until the search is done or at least [maxNodes] more
  /// states are stored. The search only stops between expansions, so the
  /// result doesn't depend on how the work is chunked. Returns [isDone].
  bool advance(int maxNodes) {
    if (_result != null) return true;
    final target = _store.length + maxNodes;
    while (true) {
      final node = _queue.pop();
      if (node < 0) {
        // Every reachable canonical state was expanded: a proof (§6.3).
        _finish(SolveVerdict.unsolvable, null);
        return true;
      }
      if (_store.isClosed(node) ||
          _store.g(node) + _store.h(node) != _queue.poppedF) {
        continue; // A stale entry: the node was rerouted since.
      }
      _expand(node);
      if (_result != null) return true;
      if (_store.length >= target) return false;
    }
  }

  void _expand(int node) {
    _store.close(node);
    _canonical.unpack(_store.chunkOf(node), _store.offsetOf(node), _parent);
    _expansions++;
    final parent = _parent;
    final child = _child;
    final canonical = _canonical;
    final g = _store.g(node) + 1;
    final h = _store.h(node);
    final totalSets = _layout.totalSets;
    final moves = _moves;
    final count = Kernel.collectLegalMoves(parent, moves);
    var lastPlacementFrom = -1;
    for (var i = 0; i < count; i++) {
      final entry = moves[i];
      final from = LegalMove.from(entry);
      final to = LegalMove.to(entry);
      final outcome = LegalMove.outcome(entry);
      final merge = MoveOutcome.isMerge(outcome);
      // A source that can be picked and is open-like is free (it is not
      // iced), and so is every placement target (an empty, usable,
      // open-like slot).
      final fromFree = Kernel.isOpenLike(parent, from);
      if (merge) {
        // The same merge the other way round was tried from the lower index.
        if (fromFree && from > to && Kernel.isOpenLike(parent, to)) continue;
      } else {
        // Spec §6.3: a lone nest from a free slot into an empty free slot
        // is pointless.
        if (fromFree) continue;
        // Every empty free slot gives the same canonical board, so one
        // placement per source is enough (design §3).
        if (from == lastPlacementFrom) continue;
        lastPlacementFrom = from;
      }
      _successors++;
      child.copyFrom(parent);
      // The entry came from the kernel's own enumeration of this board.
      Kernel.applyLegal(child, from, to, outcome);
      if (child.completedSets == totalSets) {
        _finish(SolveVerdict.solved, _solution(node));
        return;
      }

      canonical.canonicalize(child);
      _hashKey(child);
      final childH = merge ? h - 1 : h;
      final seen = _table.lookup(canonical.hashHi, canonical.hashLo, this);
      if (seen >= 0) {
        // With a consistent h an expanded node never gets cheaper; only a
        // waiting one can be rerouted (design §3).
        if (!_store.isClosed(seen) && g < _store.g(seen)) {
          _store.reroute(seen, _key, node, from, to, g);
          _reroutes++;
          _queue.push(g + childH, seen);
        }
        continue;
      }
      if (_store.length >= budget) {
        // Out of budget: never `unsolvable` (spec §6.3).
        _finish(SolveVerdict.unknown, null);
        return;
      }
      final stored = _store.add(_key, node, from, to, g, childH);
      _table.add(canonical.hashHi, canonical.hashLo, stored);
      _queue.push(g + childH, stored);
    }
  }

  /// Writes the key of the canonical [board] into [_key] and hashes it
  /// (spec §6.2: a 64-bit hash of the canonical form).
  void _hashKey(Board board) {
    _canonical
      ..writeKey(board, _key)
      ..hash(_key, _key.length);
  }

  /// Confirms a hash hit: stored [node] has the key being looked up.
  @override
  bool matches(int node) => _store.holds(node, _key);

  /// The optimal line from the real starting board to a win whose last
  /// move is made from [last]'s board: the stored nodes from the root to
  /// [last] replayed as real moves (see the class doc), then the first
  /// legal move that wins.
  List<Move> _solution(int last) {
    final path = <int>[];
    for (var n = last; _store.parent(n) >= 0; n = _store.parent(n)) {
      path.add(n);
    }
    final board = Board.copyOf(_start);
    final next = Board.copyOf(_start);
    final moves = Int32List(Kernel.legalMoveCapacity(_layout));
    final ids = _layout.ids;
    final line = <Move>[];

    // Applies the first legal move of [board] after which [reached] holds
    // for [next], the board it leads to.
    void step(bool Function() reached) {
      final count = Kernel.collectLegalMoves(board, moves);
      for (var i = 0; i < count; i++) {
        final from = LegalMove.from(moves[i]);
        final to = LegalMove.to(moves[i]);
        next.copyFrom(board);
        Kernel.tryApply(next, from, to);
        if (reached()) {
          line.add(Move(ids[from], ids[to]));
          Kernel.tryApply(board, from, to);
          return;
        }
      }
      // Unreachable: the stored move proves such a real move exists.
      throw StateError('Solver: no real move reaches the stored state');
    }

    for (final node in path.reversed) {
      step(() {
        _canonical
          ..canonicalize(next)
          ..writeKey(next, _key);
        return _store.holds(node, _key);
      });
    }
    step(() => Kernel.isWon(next));
    return List.unmodifiable(line);
  }

  void _finish(SolveVerdict verdict, List<Move>? solution) {
    _result = SolveResult(
      verdict: verdict,
      nodes: _store.length,
      branching: _expansions == 0 ? 0 : _successors / _expansions,
      solution: solution,
    );
  }
}
